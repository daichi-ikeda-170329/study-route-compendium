/** id からジャンルを引く。無い id はビルドを止める（表示だけ空になるのを防ぐ） */
export function categoryOf(id) {
  const c = CATEGORIES.find(x => x.id === id);
  if (!c) throw new Error(`知らないジャンル: ${id}（build/content/article-categories.mjs に足す）`);
  return c;
}
